// AddPermission appends a Lua-table permission spec.
func (s *Service) AddPermission(ctx context.Context, binary, kind, mode string) (writer.Result, error) {
	if binary == "" || kind == "" || mode == "" {
		return writer.Result{}, errors.New("binary, permission type and mode are required")
	}
	call := "hl.permission(" + luasrc.TableText([]luasrc.KV{
		{Key: "binary", Value: luaQuote(binary)},
		{Key: "type", Value: luaQuote(kind)},
		{Key: "mode", Value: luaQuote(mode)},
	}) + ")"
	return s.appendCall(ctx, "permission "+hex.EncodeToString([]byte(binary+"\x00"+kind)), call)
}

// AddAutostart adds one command to the hyprland.start event.
func (s *Service) AddAutostart(ctx context.Context, command string) (writer.Result, error) {
	command = strings.TrimSpace(command)
	if command == "" {
		return writer.Result{}, errors.New("autostart command is empty")
	}
	call := "hl.on(\"hyprland.start\", function()\n    hl.exec_cmd(" + luaQuote(command) + ")\nend)"
	return s.appendCall(ctx, "autostart "+hex.EncodeToString([]byte(command)), call)
}

func (s *Service) appendCall(ctx context.Context, markerID, call string) (writer.Result, error) {
	entry := s.configEntry()
	data, err := os.ReadFile(entry)
	if err != nil {
		return writer.Result{}, err
	}
	parsed := luasrc.NewFile(string(data))
	edited := luasrc.Apply(string(data), parsed.AppendMarkedCall(markerID, call))
	return s.Writer.Apply(ctx, entry, []writer.FileChange{{
		Path: entry, Content: []byte(edited), ExpectedSHA256: sourceDigest(data),
	}})
}

// SetBind creates or rewrites one keybind declaration.
//
// code must be a complete `hl.bind(...)` call, so the caller can hand-edit the
// generated Lua. When a declaration for keys already exists it is replaced in
// place, preserving the surrounding file; otherwise a marked block is appended.
func (s *Service) SetBind(ctx context.Context, keys string, code string) (writer.Result, error) {
	keys = strings.TrimSpace(keys)
	code = strings.TrimSpace(code)
	if luasrc.NormalizeCombo(keys) == "" {
		return writer.Result{}, errors.New("key combination is empty")
	}
	if !strings.HasPrefix(code, "hl.bind(") {
		return writer.Result{}, errors.New("bind code must be a complete hl.bind(...) call")
	}
	doc, err := s.LoadDocument(ctx)
	if err != nil {
		return writer.Result{}, err
	}
	file := s.configEntry()
	for _, bind := range doc.Binds {
		if luasrc.NormalizeCombo(bind.Keys) == luasrc.NormalizeCombo(keys) && bind.File != "" {
			file = bind.File
			break
		}
	}
	data, err := os.ReadFile(file)
	if err != nil {
		return writer.Result{}, err
	}
	parsed := luasrc.NewFile(string(data))
	var edits []luasrc.Edit
	if call := parsed.FindCallWithFirstArg("hl.bind", keys); call != nil {
		edits = []luasrc.Edit{{Start: call.ByteStart, End: call.ByteEnd, NewText: code}}
	} else {
		edits = []luasrc.Edit{parsed.AppendMarkedCall("bind "+hex.EncodeToString([]byte(keys)), code)}
	}
	updated := luasrc.Apply(string(data), edits...)
	return s.Writer.Apply(ctx, s.configEntry(), []writer.FileChange{{
		Path: file, Content: []byte(updated), ExpectedSHA256: sourceDigest(data),
	}})
}

func (s *Service) allowedSource(ctx context.Context, path string) (string, error) {
	doc, err := s.LoadDocument(ctx)
	if err != nil {
		return "", err
	}
	abs, err := filepath.Abs(expandHome(path))
	if err != nil {
		return "", err
	}
	entry, err := filepath.Abs(s.configEntry())
	if err != nil {
		return "", err
	}
	if filepath.Clean(abs) == filepath.Clean(entry) {
		return abs, nil
	}
	for _, file := range doc.Files {
		if filepath.Clean(file.Path) == filepath.Clean(abs) {
			return abs, nil
		}
	}
	return "", fmt.Errorf("file is not in the active Hyprland require graph: %s", abs)
}

func contains(values []string, want string) bool {
	for _, value := range values {
		if value == want {
			return true
		}
	}
	return false
}
