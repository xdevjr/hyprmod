func (s *Service) addRule(ctx context.Context, kind, function string, spec map[string]any) (writer.Result, error) {
	if len(spec) == 0 {
		return writer.Result{}, errors.New("rule spec is empty")
	}
	text, err := toLua(spec)
	if err != nil {
		return writer.Result{}, err
	}
	id := kind + " rule " + sourceDigest([]byte(text))[:12]
	return s.appendCall(ctx, id, function+"("+text+")")
}

// AddCurve defines a custom bezier or spring curve.
func (s *Service) AddCurve(ctx context.Context, name string, spec map[string]any) (writer.Result, error) {
	if strings.TrimSpace(name) == "" || len(spec) == 0 {
		return writer.Result{}, errors.New("curve name and spec are required")
	}
	text, err := toLua(spec)
	if err != nil {
		return writer.Result{}, err
	}
	return s.appendCall(ctx, "curve "+hex.EncodeToString([]byte(name)), "hl.curve("+luaQuote(name)+", "+text+")")
}

