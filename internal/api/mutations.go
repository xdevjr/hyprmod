// SourceFile is the editor's read result. Digest is used for optimistic locking
// when the user saves after editing.
type SourceFile struct {
	Path    string `json:"path"`
	Content string `json:"content"`
	Digest  string `json:"digest"`
	Bytes   int    `json:"bytes"`
}

// ReadSource returns a Lua file that belongs to the active require graph.
func (s *Service) ReadSource(ctx context.Context, path string) (SourceFile, error) {
	allowed, err := s.allowedSource(ctx, path)
	if err != nil {
		return SourceFile{}, err
	}
	data, err := os.ReadFile(allowed)
	if err != nil {
		return SourceFile{}, err
	}
	return SourceFile{Path: allowed, Content: string(data), Digest: sourceDigest(data), Bytes: len(data)}, nil
}

// WriteSource saves a raw Lua edit through the same candidate-validation,
// snapshot and atomic-write pipeline used by visual controls.
func (s *Service) WriteSource(ctx context.Context, path, content, expectedDigest string) (writer.Result, error) {
	allowed, err := s.allowedSource(ctx, path)
	if err != nil {
		return writer.Result{}, err
	}
	return s.Writer.Apply(ctx, s.configEntry(), []writer.FileChange{{
		Path: allowed, Content: []byte(content), ExpectedSHA256: expectedDigest,
	}})
}

// AddBind adds a declarative keybind. dispatcher is a path from the installed
// HL.DspNamespace catalog, e.g. "exec_cmd" or "window.close".
func (s *Service) AddBind(ctx context.Context, keys, dispatcher string, args []any, options map[string]any) (writer.Result, error) {
	keys = strings.TrimSpace(keys)
	if keys == "" {
		return writer.Result{}, errors.New("key combination is empty")
	}
	if !contains(s.Schema.Dispatchers, dispatcher) {
		return writer.Result{}, fmt.Errorf("unknown dispatcher %q", dispatcher)
	}
	argText := make([]string, 0, len(args))
	for _, arg := range args {
		text, err := toLua(arg)
		if err != nil {
			return writer.Result{}, err
		}
		argText = append(argText, text)
	}
	call := "hl.bind(" + luaQuote(keys) + ", hl.dsp." + dispatcher + "(" + strings.Join(argText, ", ") + ")"
	if len(options) > 0 {
		optionText, err := toLua(options)
		if err != nil {
			return writer.Result{}, err
		}
		call += ", " + optionText
	}
	call += ")"
	return s.appendCall(ctx, "add bind "+hex.EncodeToString([]byte(keys)), call)
}

// RemoveBind appends an hl.unbind call. Hyprland evaluates it after existing
// config modules, so it also works for binds generated by loops.
func (s *Service) RemoveBind(ctx context.Context, keys string) (writer.Result, error) {
	keys = strings.TrimSpace(keys)
	if keys == "" {
		return writer.Result{}, errors.New("key combination is empty")
	}
	return s.appendCall(ctx, "remove bind "+hex.EncodeToString([]byte(keys)), "hl.unbind("+luaQuote(keys)+")")
}

